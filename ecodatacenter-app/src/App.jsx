
import { useState, useEffect } from 'react'
import './App.css'

import {
  ResponsiveContainer,
  LineChart,
  Line,
  XAxis,
  YAxis,
  CartesianGrid,
  Tooltip,
  Legend,
} from 'recharts'

// Reusable temperature evaluation chart
function TemperatureChart({
  temperatureData,
  chartLoading,
  chartError,
  title,
}) {
  return (
    <section className="content-card chart-card">
      <div className="chart-heading">
        <div>
          <h2>{title}</h2>
          <p className="subtitle">
            Actual vs predicted temperature on the test dataset
          </p>
        </div>

        <span className="chart-unit">°C</span>
      </div>

      {chartLoading && (
        <p>Loading temperature evaluation data...</p>
      )}

      {chartError && (
        <p>
          Unable to load evaluation chart: {chartError}
        </p>
      )}

      {!chartLoading && !chartError && temperatureData.length === 0 && (
        <p>No evaluation data available.</p>
      )}

      {!chartLoading && !chartError && temperatureData.length > 0 && (
        <div className="chart-container">
          <ResponsiveContainer width="100%" height="100%">
            <LineChart data={temperatureData}>
              <CartesianGrid
                stroke="#2b3d49"
                strokeDasharray="4 4"
              />

              <XAxis
                dataKey="time"
                stroke="#91a4b0"
                tick={{ fontSize: 12 }}
              />

              <YAxis
                domain={['dataMin - 1', 'dataMax + 1']}
                stroke="#91a4b0"
                tick={{ fontSize: 12 }}
              />

              <Tooltip
                contentStyle={{
                  background: '#14232e',
                  border: '1px solid #354955',
                  borderRadius: '8px',
                  color: '#f1f5f9',
                }}
              />

              <Legend />

              <Line
                type="monotone"
                dataKey="actual"
                name="Actual Temperature"
                stroke="#72e0b8"
                strokeWidth={2.5}
                dot={false}
              />

              <Line
                type="monotone"
                dataKey="predicted"
                name="Predicted Temperature"
                stroke="#8ba8ff"
                strokeWidth={2.5}
                strokeDasharray="5 5"
                dot={false}
              />
            </LineChart>
          </ResponsiveContainer>
        </div>
      )}

      <p className="chart-note">
        Evaluation chart based on the test dataset.
        Predictions are generated by the trained LightGBM model.
        This is not a live sensor feed.
      </p>
    </section>
  )
}

